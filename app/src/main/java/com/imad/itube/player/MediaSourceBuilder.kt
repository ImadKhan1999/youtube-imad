package com.imad.itube.player

import android.net.Uri
import android.util.Log
import androidx.annotation.OptIn
import androidx.media3.common.C
import androidx.media3.common.MediaItem
import androidx.media3.common.MediaMetadata
import androidx.media3.common.MimeTypes
import androidx.media3.common.util.UnstableApi
import androidx.media3.datasource.DefaultHttpDataSource
import androidx.media3.exoplayer.dash.DashMediaSource
import androidx.media3.exoplayer.dash.DefaultDashChunkSource
import androidx.media3.exoplayer.dash.manifest.DashManifest
import androidx.media3.exoplayer.dash.manifest.DashManifestParser
import androidx.media3.exoplayer.hls.HlsMediaSource
import androidx.media3.exoplayer.source.MediaSource
import androidx.media3.exoplayer.source.MergingMediaSource
import androidx.media3.exoplayer.source.ProgressiveMediaSource
import androidx.media3.exoplayer.source.SingleSampleMediaSource
import androidx.media3.datasource.DefaultDataSource
import com.imad.itube.data.isLive
import com.imad.itube.data.net.NewPipeDownloader
import org.schabi.newpipe.extractor.services.youtube.dashmanifestcreators.YoutubeOtfDashManifestCreator
import org.schabi.newpipe.extractor.services.youtube.dashmanifestcreators.YoutubePostLiveStreamDvrDashManifestCreator
import org.schabi.newpipe.extractor.services.youtube.dashmanifestcreators.YoutubeProgressiveDashManifestCreator
import org.schabi.newpipe.extractor.stream.AudioStream
import org.schabi.newpipe.extractor.stream.DeliveryMethod
import org.schabi.newpipe.extractor.stream.Stream
import org.schabi.newpipe.extractor.stream.StreamInfo
import org.schabi.newpipe.extractor.stream.StreamType
import org.schabi.newpipe.extractor.stream.VideoStream
import java.io.ByteArrayInputStream

/**
 * Turns a [StreamInfo] plus the chosen video/audio streams into an ExoPlayer [MediaSource].
 *
 * Adaptive YouTube streams are played through small DASH manifests generated on the device by
 * NewPipeExtractor, so ExoPlayer can seek and buffer them efficiently. Nothing here ever touches
 * YouTube's ad endpoints: the player only ever receives raw media streams, so there are no ads.
 */
@OptIn(UnstableApi::class)
class MediaSourceBuilder {

    private val ytDash = YoutubeDataSource.Factory(rangeParameterEnabled = true, rnParameterEnabled = true)
    private val ytProgressive = YoutubeDataSource.Factory(rangeParameterEnabled = false, rnParameterEnabled = true)
    private val ytHls = YoutubeDataSource.Factory(rangeParameterEnabled = false, rnParameterEnabled = false)
    private val plainHttp = DefaultHttpDataSource.Factory()
        .setUserAgent(NewPipeDownloader.USER_AGENT)
        .setAllowCrossProtocolRedirects(true)

    class BuildException(message: String, cause: Throwable? = null) : Exception(message, cause)

    fun build(
        info: StreamInfo,
        video: VideoStream?,
        audio: AudioStream?,
        captions: List<CaptionOption>,
        metadata: MediaMetadata,
    ): MediaSource {
        val mediaId = info.url

        if (info.streamType.isLive()) {
            val hls = info.hlsUrl
            if (!hls.isNullOrEmpty()) {
                return HlsMediaSource.Factory(plainHttp)
                    .setAllowChunklessPreparation(true)
                    .createMediaSource(
                        MediaItem.Builder()
                            .setUri(hls)
                            .setMediaId(mediaId)
                            .setMediaMetadata(metadata)
                            .setLiveConfiguration(
                                MediaItem.LiveConfiguration.Builder().setTargetOffsetMs(10_000).build()
                            )
                            .build()
                    )
            }
            val dash = info.dashMpdUrl
            if (!dash.isNullOrEmpty()) {
                return DashMediaSource.Factory(DefaultDashChunkSource.Factory(plainHttp), plainHttp)
                    .createMediaSource(
                        MediaItem.Builder().setUri(dash).setMediaId(mediaId).setMediaMetadata(metadata).build()
                    )
            }
            throw BuildException("This live stream can't be played")
        }

        val sources = ArrayList<MediaSource>(2)
        if (video != null) sources += buildStream(info, video, metadata)
        if (audio != null && (video == null || video.isVideoOnly)) sources += buildStream(info, audio, metadata)
        if (sources.isEmpty()) throw BuildException("No playable streams found for this video")
        captions.forEach { c ->
            val config = MediaItem.SubtitleConfiguration.Builder(Uri.parse(c.url))
                .setMimeType(MimeTypes.TEXT_VTT)
                .setLanguage(c.languageTag)
                .setLabel(c.label)
                .setId(c.languageTag)
                .setRoleFlags(if (c.autoGenerated) C.ROLE_FLAG_DESCRIBES_MUSIC_AND_SOUND else C.ROLE_FLAG_CAPTION)
                .build()
            sources += SingleSampleMediaSource.Factory(plainHttp).createMediaSource(config, C.TIME_UNSET)
        }
        return if (sources.size == 1) sources[0] else MergingMediaSource(true, *sources.toTypedArray())
    }

    private fun mediaItem(stream: Stream, info: StreamInfo, metadata: MediaMetadata) =
        MediaItem.Builder()
            .setUri(Uri.parse(stream.content))
            .setMediaId(info.url)
            .setMediaMetadata(metadata)
            .build()

    private fun buildStream(info: StreamInfo, stream: Stream, metadata: MediaMetadata): MediaSource {
        val itag = stream.itagItem
        val separate = (stream is VideoStream && stream.isVideoOnly) || stream is AudioStream
        return when (stream.deliveryMethod) {
            DeliveryMethod.PROGRESSIVE_HTTP -> {
                if (separate && itag != null && info.streamType == StreamType.VIDEO_STREAM) {
                    try {
                        val manifest = YoutubeProgressiveDashManifestCreator
                            .fromProgressiveStreamingUrl(stream.content, itag, info.duration)
                        dashFromManifest(manifest, stream, info, metadata)
                    } catch (e: Exception) {
                        Log.w(TAG, "DASH manifest generation failed, using progressive source", e)
                        progressive(stream, info, metadata)
                    }
                } else if (info.streamType == StreamType.POST_LIVE_STREAM && itag != null) {
                    val manifest = YoutubePostLiveStreamDvrDashManifestCreator.fromPostLiveStreamDvrStreamingUrl(
                        stream.content, itag, itag.targetDurationSec, info.duration,
                    )
                    dashFromManifest(manifest, stream, info, metadata)
                } else {
                    progressive(stream, info, metadata)
                }
            }

            DeliveryMethod.DASH -> {
                if (!stream.isUrl && itag != null) {
                    // OTF ("on the fly") streams: content is a base URL, the manifest is ours to build.
                    val manifest = if (info.streamType == StreamType.POST_LIVE_STREAM) {
                        YoutubePostLiveStreamDvrDashManifestCreator.fromPostLiveStreamDvrStreamingUrl(
                            stream.content, itag, itag.targetDurationSec, info.duration,
                        )
                    } else {
                        YoutubeOtfDashManifestCreator.fromOtfStreamingUrl(stream.content, itag, info.duration)
                    }
                    dashFromManifest(manifest, stream, info, metadata)
                } else if (stream.isUrl) {
                    DashMediaSource.Factory(DefaultDashChunkSource.Factory(ytDash), ytDash)
                        .createMediaSource(mediaItem(stream, info, metadata))
                } else {
                    val manifest = parseManifest(stream.content, stream.manifestUrl.orEmpty())
                    DashMediaSource.Factory(DefaultDashChunkSource.Factory(ytDash), ytDash)
                        .createMediaSource(manifest, mediaItem(stream, info, metadata))
                }
            }

            DeliveryMethod.HLS -> HlsMediaSource.Factory(ytHls)
                .createMediaSource(mediaItem(stream, info, metadata))

            else -> throw BuildException("Unsupported stream type: ${stream.deliveryMethod}")
        }
    }

    /** A downloaded file (or content:// URI) played from the device. */
    fun local(context: android.content.Context, uri: Uri, mediaId: String, metadata: MediaMetadata): MediaSource =
        ProgressiveMediaSource.Factory(DefaultDataSource.Factory(context)).createMediaSource(
            MediaItem.Builder().setUri(uri).setMediaId(mediaId).setMediaMetadata(metadata).build()
        )

    private fun progressive(stream: Stream, info: StreamInfo, metadata: MediaMetadata): MediaSource =
        ProgressiveMediaSource.Factory(ytProgressive).createMediaSource(mediaItem(stream, info, metadata))

    private fun dashFromManifest(
        manifestXml: String,
        stream: Stream,
        info: StreamInfo,
        metadata: MediaMetadata,
    ): MediaSource {
        val manifest = parseManifest(manifestXml, stream.content)
        val item = MediaItem.Builder()
            .setUri(Uri.parse(stream.content))
            .setMimeType(MimeTypes.APPLICATION_MPD)
            .setMediaId(info.url)
            .setMediaMetadata(metadata)
            .build()
        return DashMediaSource.Factory(DefaultDashChunkSource.Factory(ytDash), ytDash)
            .createMediaSource(manifest, item)
    }

    private fun parseManifest(xml: String, baseUrl: String): DashManifest =
        DashManifestParser().parse(Uri.parse(baseUrl), ByteArrayInputStream(xml.toByteArray(Charsets.UTF_8)))

    private companion object {
        const val TAG = "MediaSourceBuilder"
    }
}
